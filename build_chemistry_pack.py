def overlap_area(a, b):
    x1 = max(a["x"], b["x"])
    y1 = max(a["y"], b["y"])
    x2 = min(a["x"] + a["w"], b["x"] + b["w"])
    y2 = min(a["y"] + a["h"], b["y"] + b["h"])
    if x2 <= x1 or y2 <= y1:
        return 0.0
    return (x2 - x1) * (y2 - y1)


def overlaps_any(box, existing, thresh=0.10):
    area = box["w"] * box["h"]
    if area <= 0:
        return True
    for ex in existing:
        ov = overlap_area(box, ex["bounds"])
        min_a = min(area, ex["bounds"]["w"] * ex["bounds"]["h"])
        if ov / max(min_a, 1e-6) > thresh:
            return True
    return False


def clamp_box(x, y, w, h, min_h=0.045):
    x = max(0.08, min(0.84, round(x, 4)))
    y = max(0.08, min(0.87, round(y, 4)))
    w = max(0.14, min(0.92 - x, round(w, 4)))
    h = max(min_h, min(0.89 - y, round(h, 4)))
    return {"x": x, "y": y, "w": w, "h": h}


