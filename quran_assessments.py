def build_hifz_drills():
    """Creates authentic verse-completion Hifz challenges from Tanzil for every Section 1 lesson (24:1..64)."""
    # Selected key verses for each Surah An-Nur lesson (1..13), using exact Tanzil Uthmani words!
    specs = [
        ("q-s1-01", 24, 1, "وفرضناها"),
        ("q-s1-02", 24, 4, "ثمانين"),
        ("q-s1-03", 24, 12, "خيرًا"),
        ("q-s1-04", 24, 21, "زكٰى"),
        ("q-s1-05", 24, 27, "تستئنسوا"),
        ("q-s1-06", 24, 30, "ازكى"),
        ("q-s1-07", 24, 32, "يغنهم"),
        ("q-s1-08", 24, 35, "كمشكوة"),
        ("q-s1-09", 24, 43, "يزجى"),
        ("q-s1-10", 24, 49, "مذعنين"),
        ("q-s1-11", 24, 55, "وليبدلنهم"),
        ("q-s1-12", 24, 58, "عورات"),
        ("q-s1-13", 24, 63, "لواذا"),
    ]
    from scripts.quran_text_engine import _skel
    drills = {}
    all_distractor_pool = [
        "رَءُوفٌ", "مُبَيِّنَٰتٍ", "أَزْكَىٰ", "عَلِيمٌ", "حَكِيمٌ",
        "فَٱرْجِعُوا۟", "لَّعَلَّكُمْ", "ٱلْمُفْلِحُونَ", "مُبِينٌ", "رَّحِيمٌ"
    ]
    for lid, s, a, target_hint in specs:
        v = get_ayah(s, a)["uthmani"]
        toks = v.split(" ")
        target_skel = _skel(target_hint)
        match_idx = None
        for idx, tok in enumerate(toks):
            if _skel(tok) == target_skel:
                match_idx = idx
                break
        if match_idx is None:
            # Fallback to middle substantial word (>3 chars)
            cands = [i for i, tok in enumerate(toks) if len(_skel(tok)) >= 4]
            match_idx = cands[len(cands) // 2]
        answer_word = toks[match_idx]
        masked_tokens = toks[:]
        masked_tokens[match_idx] = "〔 ……… 〕"
        distractors = [w for w in all_distractor_pool if _skel(w) != _skel(answer_word)][:3]
        opts = [answer_word] + distractors
        # Deterministic rotation based on ayah number so answer is not always 0
        shift = a % 4
        opts = opts[shift:] + opts[:shift]
        drills[lid] = {
            "lessonId": lid,
            "surah": s,
            "ayah": a,
            "audio_file": f"024{a:03d}.mp3",
            "full_uthmani": v,
            "masked_uthmani": " ".join(masked_tokens),
            "answer_word": answer_word,
            "options": opts,
            "answer": opts.index(answer_word),
        }
    return drills


