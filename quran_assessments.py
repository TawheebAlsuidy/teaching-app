def _q(qid, unit_id, lesson_id, page, diff, skill, prompt, opts, correct_idx, explain, ayah_ref=None):
    formatted_opts = []
    for i, item in enumerate(opts):
        txt, why = item
        o = {"text": txt}
        if i != correct_idx:
            o["why_wrong"] = why
        formatted_opts.append(o)
    obj = {
        "id": qid,
        "unitId": unit_id,
        "lessonId": lesson_id,
        "page": page,
        "difficulty": diff,
        "skillId": skill,
        "q": prompt,
        "options": formatted_opts,
        "answer": correct_idx,
        "explain": explain,
    }
    if ayah_ref:
        obj["ayahRef"] = ayah_ref
    return obj


