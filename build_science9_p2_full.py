    def build_unique_page_exp(bp, pdf_p, ocr_lines, u, l_pair, fallback_exp):
        exp_id = f"exp-p{bp:03d}"
        u_title = u["unit_title"] if u else "العلوم"
        l_title = l_pair[1]["title"] if l_pair else f"صفحة {bp}"

        # Filter clean OCR sentences from this specific page
        clean_ocr = []
        for ln in ocr_lines:
            t = ln["text"].strip()
            if len(t) < 12:
                continue
            if any(noise in t for noise in ["http", "نتوقع منك", "الوحدة العاشرة", "الوحدة الحادية", "الوحدة الثانية", "الوحدة الثالثة", "الوحدة الرابعة", "الوحدة الخامسة", "الوحدة السادسة", "الإدارة العامة"]):
                continue
            clean_ocr.append(t)
        ocr_snippet = " ".join(clean_ocr[:3])[:260]

        if bp in PAGE_TOPICS:
            p_title, p_summary = PAGE_TOPICS[bp]
        else:
            p_title = f"{l_title} (ص {bp})"
            p_summary = ocr_snippet if ocr_snippet else fallback_exp["original_text"]

        explanations[exp_id] = {
            "title": f"{p_title} — ص {bp}",
            "original_text": f"【محتوى صفحة {bp} — {l_title}】\n{p_summary}" + (f"\n\nمقتطف من نص الكتاب: «{ocr_snippet}»" if (ocr_snippet and bp in PAGE_TOPICS) else ""),
            "levels": {
                "basic": f"في صفحة {bp} ({p_title}): {p_summary}",
                "intermediate": f"تفصيل الدرس ({l_title} - ص {bp}): {p_summary} — {fallback_exp['levels']['intermediate']}",
                "advanced": f"التعمق العلمي (ص {bp} - {u_title}): {fallback_exp['levels']['advanced']}"
            },
            "vocabulary_ids": fallback_exp.get("vocabulary_ids", []),
            "chemical_equations": fallback_exp.get("chemical_equations", [])
        }
        return exp_id, p_title

