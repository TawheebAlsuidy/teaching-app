def load_json(name):
    with open(os.path.join(DATA_DIR, name), "r", encoding="utf-8") as f:
        return json.load(f)

def save_json(name, data):
    for d in (DATA_DIR, ANDROID_DATA_DIR):
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, name), "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

def find_ocr_y(ocr_lines, keywords, min_y=0.05, max_y=0.90, default_y=0.10):
    for ln in ocr_lines:
        if ln["y"] < min_y or ln["y"] > max_y:
            continue
        txt = ln["text"]
        if any(kw in txt for kw in keywords):
            return max(0.05, min(0.85, ln["y"] - 0.015))
    return default_y

