def build_unique_chem_diagrams():
    """Return {diag_id: diag_dict} and assert 100% uniqueness of IDs and sim_keys."""
    seen_sim = set()
    diagrams = {}
    for entry in CHEM_FIGURES:
        did = entry["id"]
        sk = entry["sim_key"]
        assert did not in diagrams, f"Duplicate diagram id: {did}"
        assert sk not in seen_sim, f"Duplicate sim_key: {sk}"
        seen_sim.add(sk)
        diagrams[did] = entry
    return diagrams


def get_unique_fig_spots_by_page():
    """Return {book_page: [figure_entry, ...]} for all 74 unique Chemistry textbook figures."""
    by_bp = {}
    for entry in CHEM_FIGURES:
        by_bp.setdefault(entry["book_page"], []).append(entry)
    return by_bp
